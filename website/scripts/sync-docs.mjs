#!/usr/bin/env node
/**
 * Publish the canonical repo-level narrative documents as docs-site guides.
 *
 * REALTIME.md and conformance/realtime.md stay canonical at the repo root;
 * this script copies them at build time into <content>/guides/, keeping
 * their relative layout, and rewrites links to files that live outside the
 * content tree (proto sources, scripts, README) to their GitHub location.
 *
 * Output targets a Nextra `content/` directory (consumed by the main website
 * at tinkle.me/schema/ — see tinkle-org/tinkle-website-nextjs). Paths:
 *   --out <dir>        content root (default: <repo>/website/content)
 *   --proto-dir <dir>  protobuf source root (default: <repo>)
 *   --repo owner/name  repository slug used for source links
 *
 * The copies are generated artifacts: <content>/guides/ is git-ignored.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  mdEscape,
  resolveContentRoot,
  resolveLinkBase,
  resolveRepoRoot,
  resolveRepoSlug,
} from './common.mjs';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const websiteRoot = path.resolve(scriptDir, '..');

// -- CLI ------------------------------------------------------------------

const argv = process.argv.slice(2);

const repoRootArg = resolveRepoRoot(argv, websiteRoot);
const contentRoot = resolveContentRoot(argv, websiteRoot);
const outGuides = path.join(contentRoot, 'guides');
const LINK_BASE = resolveLinkBase(argv);

const REPO = resolveRepoSlug({ argv, repoRootArg });
const GITHUB_MAIN = `https://github.com/${REPO}/blob/main`;

/** Strip the first top-level `# heading`; return {title, description, body}. */
function splitTitle(source, title, description) {
  const lines = String(source).split('\n');
  let start = 0;
  while (start < lines.length && lines[start].trim() === '') start += 1;
  if (start < lines.length && lines[start].startsWith('# ')) start += 1;
  const body = lines.slice(start).join('\n').replace(/^\n+/, '');
  return { title, description, body };
}

/** Turn repo-relative source-file links into GitHub links, escape MDX. */
function preprocess(body, { sourceDir }) {
  const rewritten = String(body).replace(
    /\]\(([^)\s#]+)(#[^)\s]*)?(\s+["'][^"')]*["'])?\)/g,
    (match, target, anchor = '', title = '') => {
      if (
        /^https?:\/\//.test(target) ||
        target.startsWith('#') ||
        target.startsWith('mailto:')
      ) {
        return match;
      }
      const resolved = path.posix.normalize(path.posix.join(sourceDir, target));
      const suffix = `${anchor}${title}`;
      if (resolved === 'REALTIME.md') {
        return `](${LINK_BASE}/guides/realtime${suffix})`;
      }
      if (resolved === 'conformance/realtime.md') {
        return `](${LINK_BASE}/guides/conformance/realtime${suffix})`;
      }
      if (resolved.startsWith('tinkle/') || /\.(py|toml|ya?ml|json|txt|md|sh|mjs)$/.test(resolved)) {
        return `](${GITHUB_MAIN}/${resolved}${suffix})`;
      }
      return match;
    },
  );
  return mdEscape(rewritten);
}

function writeFile(rel, front, content) {
  const file = path.join(outGuides, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, front + content, 'utf8');
}

// ----------------------------------------------------------------- actions

function main() {
  fs.rmSync(outGuides, { recursive: true, force: true });
  fs.mkdirSync(outGuides, { recursive: true });

  fs.writeFileSync(
    path.join(outGuides, '_meta.js'),
    '// Generated by website/scripts/sync-docs.mjs — do not edit.\n' +
      'export default {\n' +
      "  realtime: 'Realtime application binding',\n" +
      "  conformance: 'Realtime conformance',\n" +
      '}\n',
    'utf8',
  );

  const realtime = fs.readFileSync(path.join(repoRootArg, 'REALTIME.md'), 'utf8');
  const conformance = fs.readFileSync(
    path.join(repoRootArg, 'conformance', 'realtime.md'),
    'utf8',
  );

  const rt = splitTitle(
    realtime,
    'Realtime application binding',
    'The Syntra-only realtime application binding: normative requirements.',
  );
  writeFile(
    'realtime.mdx',
    '---\n' +
      `title: "${String(rt.title).replace(/"/g, '\\"')}"\n` +
      `description: "${String(rt.description).replace(/"/g, '\\\\"')}"\n` +
      '---\n',
    preprocess(rt.body, { sourceDir: '.' }),
  );

  const cf = splitTitle(
    conformance,
    'Realtime schema conformance',
    'Implementation checks for the batched realtime binding.',
  );
  writeFile(
    'conformance/realtime.mdx',
    '---\n' +
      `title: "${String(cf.title).replace(/"/g, '\\"')}"\n` +
      `description: "${String(cf.description).replace(/"/g, '\\\\"')}"\n` +
      '---\n',
    preprocess(cf.body, { sourceDir: 'conformance' }),
  );

  console.log(`sync-docs: published REALTIME.md and conformance/realtime.md into ${path.relative(process.cwd(), outGuides) || outGuides} (repo ${REPO})`);
}

main();
